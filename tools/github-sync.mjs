// Publish task briefs once. Beads owns execution state; GitHub retains human discussion.
import { join } from 'node:path';
import { mkdir, writeFile } from 'node:fs/promises';
import { root, exec, atomicJSON, acquireLock } from './workflow/core.mjs';
const repo = 'Jbudone/yendor';
const release = await acquireLock(root, 'github-publish');
try {
  await exec('gh', ['label', 'create', 'needs-triage', '--repo', repo, '--color', 'FBCA04', '--description', 'Evaluate scope and evidence before implementation', '--force']);
  const { stdout } = await exec(join(root, '.tools/bin/bd'), ['list', '--all', '--json'], { cwd: root, maxBuffer: 4_000_000, timeout: 120_000 });
  const tasks = JSON.parse(stdout);
  const { stdout: issueData } = await exec('gh', ['issue', 'list', '--repo', repo, '--state', 'all', '--limit', '1000', '--json', 'number,body,url']);
  const issues = JSON.parse(issueData);
  await mkdir(join(root, 'artifacts/github'), { recursive: true });
  const mapping = {};
  for (const task of tasks) {
    const marker = `<!-- yendor-beads:${task.id} -->`;
    let issue = issues.find(issue => issue.body.includes(marker));
    if (!issue) {
      const body = `> *This was generated by AI during triage.*\n\n${marker}\nBeads task: \`${task.id}\`\n\n${task.description || ''}\n\nAcceptance:\n${task.acceptance_criteria || 'Record actual evidence, limitations and a durable handoff.'}\n\nExecution status and dependencies are maintained in Beads. This issue preserves user discussion and direction. Changes here should be reviewed into the task brief before implementation.\n`;
      const path = join(root, 'artifacts/github', `${task.id}.md`); await writeFile(path, body);
      const { stdout: url } = await exec('gh', ['issue', 'create', '--repo', repo, '--title', task.title, '--body-file', path, '--label', 'enhancement', '--label', 'needs-triage']);
      issue = { url: url.trim(), number: Number(url.trim().split('/').at(-1)), body }; issues.push(issue);
    }
    mapping[task.id] = { issue: issue.number, url: issue.url };
    console.log(`${task.id} → ${issue.url}`);
  }
  await atomicJSON(join(root, 'config/github-task-map.json'), { repo, updatedAt: new Date().toISOString(), tasks: mapping });
} finally { await release(); }
